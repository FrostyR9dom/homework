/**
 * server.js
 * 
 * ГЛАВНЫЙ ФАЙЛ СЕРВЕРА
 * 
 * НАЗНАЧЕНИЕ:
 * Запускает веб-сервер, подключает все маршруты (роуты),
 * настраивает middleware (промежуточные обработчики).
 * 
 * КАК ЗАПУСТИТЬ:
 * 1. Установить Node.js с официального сайта nodejs.org
 * 2. Открыть терминал в папке backend/
 * 3. Выполнить: npm install
 * 4. Выполнить: npm start
 * 5. Сервер будет доступен по адресу http://localhost:3000
 */

// Загружаем переменные окружения из файла .env
require('dotenv').config();

// Подключаем необходимые библиотеки
const express = require('express'); // Сам веб-сервер
const cors = require('cors'); // Для разрешения запросов с фронтенда
const path = require('path'); // Для работы с путями файлов
const rateLimit = require('express-rate-limit'); // Защита от DDoS

// Создаём приложение Express
const app = express();

// ============================================================
// НАСТРОЙКА MIDDLEWARE
// ============================================================

/**
 * CORS - разрешает запросы с нашего фронтенда
 * 
 * Без этого браузер будет блокировать запросы
 * с localhost:5500 (фронтенд) к localhost:3000 (бэкенд)
 */
app.use(cors({
    origin: ['http://localhost:5500', 'http://127.0.0.1:5500', 'http://localhost:3000'],
    credentials: true
}));

/**
 * Парсинг JSON в теле запроса
 * 
 * Когда фронтенд отправляет данные (например, при регистрации),
 * они приходят в формате JSON. Эта строка автоматически
 * преобразует JSON в JavaScript объект.
 */
app.use(express.json({ limit: '10mb' }));

/**
 * Раздача статических файлов
 * 
 * Все файлы из папки uploads будут доступны по URL
 * Например: /uploads/photo123.jpg
 */
app.use('/uploads', express.static(path.join(__dirname, 'uploads')));

/**
 * Защита от частых запросов (Rate Limiting)
 * 
 * Не даёт злоумышленникам отправлять тысячи запросов в минуту.
 * Для авторизации - максимум 5 запросов за 15 минут.
 */
const authLimiter = rateLimit({
    windowMs: 15 * 60 * 1000, // 15 минут
    max: 5, // Максимум 5 запросов
    message: { error: 'Слишком много запросов. Попробуйте позже.' }
});

// ============================================================
// ПОДКЛЮЧЕНИЕ МАРШРУТОВ (РОУТОВ)
// ============================================================

/**
 * Каждый файл в папке routes/ отвечает за свою часть API:
 * - auth.js: регистрация и вход по телефону
 * - routes.js: создание, получение, фильтрация маршрутов
 * - users.js: профиль пользователя, настройки
 * - gallery.js: загрузка и просмотр фото
 * - forum.js: темы и сообщения форума
 */

const authRoutes = require('./routes/auth');
const routeRoutes = require('./routes/routes');
const userRoutes = require('./routes/users');
const galleryRoutes = require('./routes/gallery');
const forumRoutes = require('./routes/forum');

// Подключаем роуты к приложению
app.use('/api/auth', authLimiter, authRoutes); // С ограничением запросов
app.use('/api/routes', routeRoutes);
app.use('/api/users', userRoutes);
app.use('/api/gallery', galleryRoutes);
app.use('/api/forum', forumRoutes);

// ============================================================
// ТЕСТОВЫЙ МАРШРУТ (для проверки работы сервера)
// ============================================================
app.get('/api/health', (req, res) => {
    res.json({
        status: 'ok',
        message: 'Сервер СвояТропа работает!',
        timestamp: new Date().toISOString()
    });
});

// ============================================================
// ОБРАБОТКА ОШИБОК
// ============================================================

/**
 * Если запрошен несуществующий маршрут - возвращаем 404
 */
app.use((req, res) => {
    res.status(404).json({ error: 'Маршрут не найден на сервере' });
});

/**
 * Глобальный обработчик ошибок
 * Ловит все необработанные ошибки и возвращает их в JSON
 */
app.use((err, req, res, next) => {
    console.error('❌ Ошибка сервера:', err);
    res.status(500).json({ error: 'Внутренняя ошибка сервера' });
});

// ============================================================
// ЗАПУСК СЕРВЕРА
// ============================================================

const PORT = process.env.PORT || 3000;

app.listen(PORT, () => {
    console.log('=========================================');
    console.log('🌲 Сервер "СвояТропа" запущен!');
    console.log(`📍 Адрес: http://localhost:${PORT}`);
    console.log(`📊 API: http://localhost:${PORT}/api`);
    console.log('=========================================');
});